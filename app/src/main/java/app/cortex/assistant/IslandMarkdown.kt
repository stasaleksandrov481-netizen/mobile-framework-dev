package app.cortex.assistant

import android.graphics.Color
import android.graphics.Typeface
import android.text.SpannableStringBuilder
import android.text.Spanned
import android.text.style.BackgroundColorSpan
import android.text.style.ForegroundColorSpan
import android.text.style.RelativeSizeSpan
import android.text.style.StrikethroughSpan
import android.text.style.StyleSpan
import android.text.style.TypefaceSpan
import android.text.style.URLSpan

/** Small, strictly text-only Markdown renderer for the floating island.
 *
 * No WebView, remote content, image downloads or HTML interpretation. The
 * partial input generated by a streaming assistant is valid at every frame.
 */
internal object IslandMarkdown {
    private val heading = Regex("""^(#{1,4})\s+""")
    private val bullet = Regex("""^\s*[-*+]\s+""")
    private val numbered = Regex("""^\s*(\d{1,3})[.)]\s+""")
    private val task = Regex("""^\s*[-*+]\s+\[([ xX])\]\s+""")
    private val link = Regex("""^\[([^\]\n]{1,120})\]\((https?://[^\s)<>]{1,1500})\)""")
    private val tableSeparator = Regex("""^:?-{3,}:?$""")
    private val INLINE_TOKENS = arrayOf("**", "__", "~~", "*", "_")
    private val RULES = setOf("---", "***", "___")
    private val callout = Regex("""^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)]\s*""")
    private const val MAX_VISIBLE = 24_000
    private val MONO_BG = 0xFF191919.toInt()
    private val MUTED = 0xFFACACAC.toInt()

    fun render(source: String, accent: Int = Color.WHITE): CharSequence {
        val result = SpannableStringBuilder()
        var fence: String? = null
        // A native TextView must never interpret arbitrary model HTML or CSS.
        // UI fences are presented as semantic text instead of raw DSL lines.
        for (raw in source.take(MAX_VISIBLE).lineSequence()) {
            val trimmed = raw.trim()
            val marker = trimmed.takeWhile { it == '`' || it == '~' }
            if (marker.length >= 3 && marker.all { it == marker[0] }) {
                if (fence == null) fence = if (trimmed.drop(marker.length).trim() == "cortex-ui") "ui" else "code"
                else fence = null
                continue
            }
            val rich = if (fence == "ui") richText(raw) else null
            if (fence == "ui" && rich == null) continue
            val cells = raw.trim().takeIf { it.startsWith('|') && it.endsWith('|') }
                ?.trim('|')?.split('|')?.map { it.trim() }
            if (fence == null && cells != null && cells.all { tableSeparator.matches(it) }) continue
            if (result.isNotEmpty()) result.append('\n')
            val start = result.length
            if (fence == "code") {
                result.append(raw.ifEmpty { " " })
                decorateCode(result, start, result.length, block = true)
                continue
            }
            if (fence == "ui") {
                appendInline(result, rich.orEmpty(), accent)
                if (trimmed.startsWith("title |") && result.length > start) {
                    result.setSpan(StyleSpan(Typeface.BOLD), start, result.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                    result.setSpan(RelativeSizeSpan(1.12f), start, result.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                }
                continue
            }
            val header = heading.find(raw)
            val checked = task.find(raw)
            val ordered = numbered.find(raw)
            val unordered = bullet.find(raw)
            val quote = raw.trimStart().startsWith("> ")
            val horizontalRule = raw.trim() in RULES
            when {
                horizontalRule -> result.append("────────────")
                cells != null -> {
                    appendInline(result, cells.joinToString("   ·   "), accent)
                    if (result.length > start) result.setSpan(RelativeSizeSpan(.94f), start, result.length,
                        Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                }
                header != null -> appendInline(result, raw.substring(header.value.length), accent)
                checked != null -> {
                    result.append(if (checked.groupValues[1].isBlank()) "☐  " else "☑  ")
                    appendInline(result, raw.substring(checked.value.length), accent)
                }
                ordered != null -> {
                    result.append(ordered.groupValues[1]).append(".  ")
                    appendInline(result, raw.substring(ordered.value.length), accent)
                }
                unordered != null -> {
                    result.append("•  ")
                    appendInline(result, raw.substring(unordered.value.length), accent)
                }
                quote -> {
                    val quoted = raw.trimStart().removePrefix("> ").trimStart()
                    val calloutMatch = callout.find(quoted)
                    if (calloutMatch != null) {
                        val title = when (calloutMatch.groupValues[1]) {
                            "TIP" -> "Совет"; "IMPORTANT" -> "Важно"; "WARNING" -> "Внимание"
                            "CAUTION" -> "Осторожно"; else -> "Заметка"
                        }
                        result.append("│  ").append(title)
                        val detail = quoted.removePrefix(calloutMatch.value).trim()
                        if (detail.isNotBlank()) {
                            result.append(" · ")
                            appendInline(result, detail, accent)
                        }
                    } else {
                        result.append("│  ")
                        appendInline(result, quoted, accent)
                    }
                }
                else -> appendInline(result, raw, accent)
            }
            if (result.length > start) {
                when {
                    header != null -> {
                        result.setSpan(StyleSpan(Typeface.BOLD), start, result.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                        result.setSpan(RelativeSizeSpan(if (header.groupValues[1].length == 1) 1.22f else 1.1f),
                            start, result.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                    }
                    quote || horizontalRule -> result.setSpan(ForegroundColorSpan(MUTED), start, result.length,
                        Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                }
            }
        }
        return result
    }

    /** Compact native presentation for composable assistant widgets.
     * No arbitrary markup or user-controlled Android View creation.
     */
    private fun richText(raw: String): String? {
        val fields = raw.split('|').map { it.trim() }
        val data = fields.drop(1)
        fun field(index: Int) = data.getOrNull(index).orEmpty().take(180)
        return when (fields.firstOrNull().orEmpty()) {
            "grid", "stack", "row", "end", "divider" -> null
            "title", "section" -> field(0)
            "stat" -> listOf(field(0), field(1), field(2)).filter(String::isNotBlank).joinToString("  ·  ")
            "kv", "score" -> field(0) + ": " + field(1) + (if (fields[0] == "score") " / " + field(2) else "")
            "bar", "donut" -> field(0) + "  ·  " + (field(2).ifBlank { field(1) + "%" })
            "trend" -> field(0) + (if (field(2).isNotBlank()) "  ·  " + field(2) else "")
            "step" -> "•  " + field(1) + (if (field(2).isNotBlank()) " — " + field(2) else "")
            "notice" -> field(1) + (if (field(2).isNotBlank()) " — " + field(2) else "")
            "tag" -> field(0)
            "compare" -> field(0) + " → " + field(1)
            "quote" -> "│  " + field(0) + (if (field(1).isNotBlank()) " — " + field(1) else "")
            "flow" -> data.take(5).joinToString(" → ")
            else -> data.ifEmpty { fields }.take(5).joinToString(" · ").take(320)
        }.take(420)
    }

    private fun appendInline(out: SpannableStringBuilder, input: String, accent: Int, depth: Int = 0) {
        var index = 0
        while (index < input.length) {
            if (input[index] == '\\' && index + 1 < input.length && input[index + 1] in "*`_~[]\\") {
                out.append(input[index + 1]); index += 2; continue
            }
            if (input[index] == '`') {
                val close = input.indexOf('`', index + 1)
                if (close > index + 1) {
                    val start = out.length
                    out.append(input.substring(index + 1, close))
                    decorateCode(out, start, out.length, block = false)
                    index = close + 1
                    continue
                }
            }
            if (input[index] == '[') {
                val match = link.find(input.substring(index))
                if (match != null) {
                    val url = match.groupValues[2]
                    if (url.length <= 1500 && !url.contains('@')) {
                        val start = out.length
                        out.append(match.groupValues[1])
                        out.setSpan(URLSpan(url), start, out.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                        out.setSpan(ForegroundColorSpan(accent), start, out.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                        out.setSpan(StyleSpan(Typeface.BOLD), start, out.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                        index += match.value.length
                        continue
                    }
                }
            }
            if (depth < 3) {
                var parsed = false
                for (token in INLINE_TOKENS) {
                    if (!input.startsWith(token, index)) continue
                    val close = input.indexOf(token, index + token.length)
                    if (close <= index + token.length) continue
                    val start = out.length
                    appendInline(out, input.substring(index + token.length, close), accent, depth + 1)
                    if (out.length > start) {
                        val span = when (token) {
                            "**", "__" -> StyleSpan(Typeface.BOLD)
                            "~~" -> StrikethroughSpan()
                            else -> StyleSpan(Typeface.ITALIC)
                        }
                        out.setSpan(span, start, out.length, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
                    }
                    index = close + token.length
                    parsed = true
                    break
                }
                if (parsed) continue
            }
            out.append(input[index])
            index++
        }
    }

    private fun decorateCode(out: SpannableStringBuilder, start: Int, end: Int, block: Boolean) {
        if (end <= start) return
        out.setSpan(TypefaceSpan("monospace"), start, end, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
        out.setSpan(BackgroundColorSpan(MONO_BG), start, end, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
        out.setSpan(ForegroundColorSpan(0xFFE8E8E8.toInt()), start, end, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
        out.setSpan(RelativeSizeSpan(if (block) .88f else .91f), start, end, Spanned.SPAN_EXCLUSIVE_EXCLUSIVE)
    }
}
